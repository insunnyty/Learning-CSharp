// Igual
int x = 10;
int y = 10;

if (x == y)
{
    Console.WriteLine("x é igual a y");
}
else
{
    Console.WriteLine("x não é igual a y");
}

// Diferente (Não igual)
string player1 = "Alice";
string player2 = "Bob";

if (player1 != player2)
{
    Console.WriteLine("Os jogadores são diferentes.");
}
else
{
    Console.WriteLine("Os jogadores são iguais.");
}

// Maior que
int age1 = 30;
int age2 = 20;

if (age1 > age2)
{
    Console.WriteLine($"{age1} é maior que {age2}");
}
else
{
    Console.WriteLine($"{age1} não é maior que {age2}");
}

// Maior ou igual a
int score1 = 85;
int score2 = 90;

if (score1 >= score2)
{
    Console.WriteLine($"{score1} é maior ou igual a {score2}");
}
else
{
    Console.WriteLine($"{score1} não é maior ou igual a {score2}");
}

// Menor que
int temperature1 = 15;
int temperature2 = 20;

if (temperature1 < temperature2)
{
    Console.WriteLine($"{temperature1} é menor que {temperature2}");
}
else
{
    Console.WriteLine($"{temperature1} não é menor que {temperature2}");
}

// Menor ou igual a
int height1 = 170;
int height2 = 180;

if (height1 <= height2)
{
    Console.WriteLine($"{height1} é menor ou igual a {height2}");
}
else
{
    Console.WriteLine($"{height1} não é menor ou igual a {height2}");
}

